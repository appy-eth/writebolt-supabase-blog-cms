/**
 * Interactive setup: writes .env.local and prints next steps.
 * Run: npm run setup
 */

import * as fs from "fs";
import * as path from "path";
import * as readline from "readline";
import { randomBytes } from "crypto";

const root = process.cwd();

function question(rl: readline.Interface, q: string): Promise<string> {
  return new Promise((resolve) => rl.question(q, resolve));
}

function requirePackageJson(): void {
  const pkg = path.join(root, "package.json");
  if (!fs.existsSync(pkg)) {
    console.error(
      "\n❌ No package.json in this folder.\n\n" +
        "You must clone the full Writebolt blog repository (it includes Next.js, package.json, app/, etc.).\n" +
        "If you only see a README on GitHub, the app source was not pushed — fix the repo or clone from the correct branch.\n"
    );
    process.exit(1);
  }
}

function generateEncryptionKey(): string {
  return randomBytes(32).toString("hex");
}

async function main() {
  requirePackageJson();

  const rl = readline.createInterface({
    input: process.stdin,
    output: process.stdout,
  });

  console.log("\n⚡ Writebolt Blog — setup wizard\n");
  console.log(
    "You need your Supabase project URL and keys (Settings → API on supabase.com).\n"
  );

  const envPath = path.join(root, ".env.local");
  if (fs.existsSync(envPath)) {
    const overwrite = (await question(
      rl,
      ".env.local already exists. Overwrite? [y/N]: "
    ))
      .trim()
      .toLowerCase();
    if (overwrite !== "y" && overwrite !== "yes") {
      console.log("Aborted. Edit .env.local manually or delete it and run again.");
      rl.close();
      return;
    }
  }

  const url = (await question(rl, "NEXT_PUBLIC_SUPABASE_URL: ")).trim();
  const anon = (await question(rl, "NEXT_PUBLIC_SUPABASE_ANON_KEY: ")).trim();
  const service = (await question(rl, "SUPABASE_SERVICE_ROLE_KEY: ")).trim();

  if (!url || !anon || !service) {
    console.error("\n❌ All three values are required.\n");
    rl.close();
    process.exit(1);
  }

  const encryptionKey = generateEncryptionKey();

  const contents = `# Generated by npm run setup — do not commit this file
NEXT_PUBLIC_SUPABASE_URL=${url}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${anon}
SUPABASE_SERVICE_ROLE_KEY=${service}

# Used to encrypt BYOK API keys in the admin AI settings UI
SETTINGS_ENCRYPTION_KEY=${encryptionKey}

# Optional — or configure keys in Admin → AI Config
# OPENAI_API_KEY=
# REPLICATE_API_KEY=
`;

  fs.writeFileSync(envPath, contents, "utf8");
  console.log("\n✅ Wrote .env.local (and generated SETTINGS_ENCRYPTION_KEY).\n");

  const sqlPath = path.join(
    root,
    "supabase",
    "migrations",
    "001_writebolt_blog_schema.sql"
  );
  console.log("── Next steps ─────────────────────────────────────────");
  console.log("1. Supabase → SQL Editor → New query");
  console.log(`2. Paste the contents of:\n   ${sqlPath}`);
  console.log("3. Run the query (creates tables + RLS policies).");
  console.log("4. Then run:  npm run seed");
  console.log("5. Then run:  npm run dev");
  console.log("────────────────────────────────────────────────────────\n");

  rl.close();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
