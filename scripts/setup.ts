/**
 * Interactive setup: writes .env.local, optionally re-seeds the database.
 * Run: npm run setup
 * Re-run seed only (after migrations): npm run setup -- --seed
 */

import * as fs from "fs";
import * as path from "path";
import * as readline from "readline";
import { randomBytes } from "crypto";
import { config } from "dotenv";
import { seed } from "./seed";

const root = process.cwd();
const envPath = path.join(root, ".env.local");

function question(rl: readline.Interface, q: string): Promise<string> {
  return new Promise((resolve) => rl.question(q, resolve));
}

function requirePackageJson(): void {
  const pkg = path.join(root, "package.json");
  if (!fs.existsSync(pkg)) {
    console.error(
      "\n❌ No package.json in this folder.\n\n" +
        "• Recommended: cd into writebolt-astro/ and use npm install && npm run setup (Astro template).\n" +
        "• This script is for the Next.js app at the repository root (clone must include package.json, app/, etc.).\n" +
        "If you only see a README on GitHub, the app source was not pushed — fix the repo or clone from the correct branch.\n"
    );
    process.exit(1);
  }
}

function generateEncryptionKey(): string {
  return randomBytes(32).toString("hex");
}

/** Escape a value for a double-quoted .env line. */
function escapeEnvDoubleQuoted(value: string): string {
  return `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

async function runSeedSafe(context: string): Promise<void> {
  try {
    config({ path: envPath, override: true });
    await seed();
    console.log(`\n✅ Seed completed (${context}).\n`);
  } catch (e) {
    const msg = e instanceof Error ? e.message : String(e);
    console.warn(
      `\n⚠️  Seed skipped or failed (${context}): ${msg}\n` +
        "   This is OK if migrations are not applied yet.\n" +
        "   After you run the SQL migration in Supabase SQL Editor, run:\n" +
        "     npm run setup -- --seed\n"
    );
  }
}

async function seedOnlyMode(): Promise<void> {
  requirePackageJson();
  if (!fs.existsSync(envPath)) {
    console.error(
      "\n❌ .env.local not found. Run `npm run setup` first to create it.\n"
    );
    process.exit(1);
  }
  console.log("\n⚡ Writebolt Blog — seed only\n");
  try {
    config({ path: envPath, override: true });
    await seed();
    console.log("\nDone.\n");
  } catch (e) {
    console.error(e);
    process.exit(1);
  }
}

async function wizardMode(): Promise<void> {
  requirePackageJson();

  const rl = readline.createInterface({
    input: process.stdin,
    output: process.stdout,
  });

  console.log("\n⚡ Writebolt Blog — setup wizard\n");
  console.log(
    "Have your Supabase project URL and keys ready (Settings → API on supabase.com).\n\n" +
      "Important: apply the SQL migration in Supabase **before** seed can succeed:\n" +
      "  Open Supabase → SQL Editor → paste and run `supabase/migrations/001_writebolt_blog_schema.sql`\n" +
      "  Already on the old Next.js schema? Also run `supabase/migrations/002_align_astro_schema.sql`\n"
  );

  if (fs.existsSync(envPath)) {
    const overwrite = (await question(
      rl,
      ".env.local already exists. Overwrite? [y/N]: "
    ))
      .trim()
      .toLowerCase();
    if (overwrite !== "y" && overwrite !== "yes") {
      console.log(
        "Aborted. To re-run only the seed after migrations: npm run setup -- --seed"
      );
      rl.close();
      return;
    }
  }

  const url = (await question(rl, "NEXT_PUBLIC_SUPABASE_URL: ")).trim();
  const anon = (await question(rl, "NEXT_PUBLIC_SUPABASE_ANON_KEY: ")).trim();
  const service = (await question(rl, "SUPABASE_SERVICE_ROLE_KEY: ")).trim();
  const newsletterKey = (
    await question(
      rl,
      "NEWSLETTER_API_KEY (optional — for /api/newsletter/subscribe; press Enter to skip): "
    )
  ).trim();

  const defaultAdminUser = "youradmin";
  const adminUserRaw = (
    await question(
      rl,
      `ADMIN_USERNAME [${defaultAdminUser}]: `
    )
  ).trim();
  const adminUser = adminUserRaw || defaultAdminUser;

  const adminPass = (
    await question(
      rl,
      "ADMIN_PASSWORD (strong, unique — required for /admin login): "
    )
  ).trim();

  if (!url || !anon || !service) {
    console.error("\n❌ All three Supabase values are required.\n");
    rl.close();
    process.exit(1);
  }

  if (!adminPass) {
    console.error("\n❌ ADMIN_PASSWORD is required.\n");
    rl.close();
    process.exit(1);
  }

  const encryptionKey = generateEncryptionKey();

  const newsletterLine = newsletterKey
    ? `NEWSLETTER_API_KEY=${newsletterKey}\n`
    : `# NEWSLETTER_API_KEY=\n`;

  const adminUserLine = /^[\w.-]+$/i.test(adminUser)
    ? `ADMIN_USERNAME=${adminUser}`
    : `ADMIN_USERNAME=${escapeEnvDoubleQuoted(adminUser)}`;

  const contents = `# Generated by npm run setup — do not commit this file
NEXT_PUBLIC_SUPABASE_URL=${url}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${anon}
SUPABASE_SERVICE_ROLE_KEY=${service}

# Admin panel sign-in (use requireAdminApi on /api/admin routes)
${adminUserLine}
ADMIN_PASSWORD=${escapeEnvDoubleQuoted(adminPass)}

# Used to encrypt BYOK API keys in the admin AI settings UI
SETTINGS_ENCRYPTION_KEY=${encryptionKey}

# Optional — newsletter provider integrations (see README)
${newsletterLine}
# Optional — or configure keys in Admin → AI Config
# OPENAI_API_KEY=
# REPLICATE_API_KEY=
`;

  fs.writeFileSync(envPath, contents, "utf8");
  console.log("\n✅ Wrote .env.local (generated SETTINGS_ENCRYPTION_KEY).\n");

  rl.close();

  await runSeedSafe("post-setup");

  console.log("── Next steps ─────────────────────────────────────────");
  console.log("1. Ensure migration 001 has been run in Supabase.");
  console.log("2. If seed warned above, run:  npm run setup -- --seed");
  console.log("3. Start the app:              npm run dev");
  console.log(
    "4. Open http://localhost:3000 — sign in at /admin with the admin credentials above."
  );
  console.log("────────────────────────────────────────────────────────\n");
}

async function main() {
  const args = process.argv.slice(2);
  if (args.includes("--seed")) {
    await seedOnlyMode();
    return;
  }
  await wizardMode();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
