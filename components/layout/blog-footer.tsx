import type { BlogSettings } from "@/types";
import { NewsletterSignup } from "@/components/callouts/newsletter-signup";

interface BlogFooterProps {
  settings: BlogSettings;
}

export function BlogFooter({ settings }: BlogFooterProps) {
  const socialLinks = [
    { url: settings.social_twitter, label: "Twitter", icon: TwitterIcon },
    { url: settings.social_linkedin, label: "LinkedIn", icon: LinkedInIcon },
    { url: settings.social_github, label: "GitHub", icon: GitHubIcon },
    { url: settings.social_youtube, label: "YouTube", icon: YouTubeIcon },
    { url: settings.social_website, label: "Website", icon: GlobeIcon },
  ].filter((link) => link.url);

  return (
    <footer className="border-t border-gray-200 bg-white dark:border-gray-800 dark:bg-gray-950">
      <div className="mx-auto max-w-7xl px-4 py-8 sm:px-6 lg:px-8">
        {/* Newsletter in footer */}
        {settings.newsletter_enabled &&
          (settings.newsletter_embed_url?.trim() ||
            settings.newsletter_list_id?.trim()) && (
            <div className="mb-8 border-b border-gray-200 pb-8 dark:border-gray-800">
              <NewsletterSignup
                embedUrl={settings.newsletter_embed_url}
                listId={settings.newsletter_list_id}
                successMessage={settings.newsletter_success_message}
                successRedirectUrl={settings.newsletter_success_redirect_url}
                emailPlaceholder="Enter your email"
                variant="footer"
              />
            </div>
          )}

        <div className="flex flex-col items-center justify-between gap-4 sm:flex-row">
          <p className="text-sm text-gray-500 dark:text-gray-400">
            &copy; {new Date().getFullYear()} {settings.site_name}. All
            rights reserved.
          </p>

          {socialLinks.length > 0 && (
            <div className="flex items-center gap-4">
              {socialLinks.map((link) => (
                <a
                  key={link.label}
                  href={link.url!}
                  target="_blank"
                  rel="noopener noreferrer"
                  className="text-gray-400 transition-colors hover:text-gray-600 dark:text-gray-500 dark:hover:text-gray-300"
                  aria-label={link.label}
                >
                  <link.icon className="h-5 w-5" />
                </a>
              ))}
            </div>
          )}
        </div>
      </div>
    </footer>
  );
}

